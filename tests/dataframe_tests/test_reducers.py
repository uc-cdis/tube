import pytest

import tube.settings as config
from tube.utils.spark import make_spark_context
from tube.etl.indexers.base.translator import Translator


@pytest.fixture(scope="module")
def spark_context():
    return make_spark_context(config)


@pytest.mark.parametrize(
    "fn,expected_fn_name",
    [
        ("min", "min"),
        ("max", "max"),
        ("sum", "sum"),
        ("count", "count"),
    ],
)
def test_reducer_uses_matching_aggregate_function(spark_context, fn, expected_fn_name):
    """
    Regression test for the `max` reducer silently computing a minimum.

    `reducer_to_agg_func_expr` returned `min(col(value))` for BOTH `fn: min` and
    `fn: max`, so every `fn: max` aggregated_prop in an etlMapping shipped the
    wrong value to Guppy. It went unnoticed because the (now dead) RDD
    implementation in base/lambdas.py was correct, and because the
    dataframe_tests fixtures were generated by the same buggy code.

    The root cause was a missing import: `max` was never imported from
    pyspark.sql.functions, so writing `max(...)` would have used the Python
    builtin. Asserting on the rendered Column expression catches both the
    wrong-aggregate bug and a regression back to the builtin.
    """
    expr = Translator.reducer_to_agg_func_expr(fn, "some_field", alias="out")
    rendered = str(expr).lower()

    assert (
        expected_fn_name in rendered
    ), "reducer {!r} rendered as {!r}, expected the {!r} aggregate".format(
        fn, str(expr), expected_fn_name
    )


def test_max_reducer_is_not_min(spark_context):
    """
    Explicit guard on the exact regression: `max` must not render as `min`.
    """
    max_expr = str(Translator.reducer_to_agg_func_expr("max", "age", alias="out"))
    min_expr = str(Translator.reducer_to_agg_func_expr("min", "age", alias="out"))

    assert (
        max_expr != min_expr
    ), "`max` and `min` reducers produced identical expressions: {!r}".format(max_expr)
